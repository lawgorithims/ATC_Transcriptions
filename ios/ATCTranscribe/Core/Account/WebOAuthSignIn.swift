import AuthenticationServices
import CryptoKit
import Foundation

/// Google sign-in, run through the website's existing OAuth flow in a system browser sheet.
///
/// # Why this is not a Google SDK
///
/// The website already does the whole Google dance — client id, token exchange, account linking in
/// `findOrCreateUserFromOAuth`. Adding GoogleSignIn-iOS would mean a second implementation of the
/// same thing, a third-party SDK in an app that currently has none in its auth path, and a second
/// place for the account-linking rules to drift. `ASWebAuthenticationSession` reuses what is
/// already there and shipping.
///
/// # Why a code exchange and not a token in the callback URL
///
/// The obvious version of this has the server redirect to `obelisk://auth/callback?token=…`. That
/// would be a real leak: the redirect is generated by our own server, and the reverse proxy in
/// front of it logs query strings — so every sign-in would write a live 30-day session token into
/// a log file on the box.
///
/// So the callback carries a one-time code, and this type holds a PKCE-style verifier that never
/// leaves the device except in the body of one TLS POST. A code scraped from a proxy log is inert
/// without it. The server half is `lib/auth/native-handoff.ts`.
@MainActor
final class WebOAuthSignIn: NSObject, ASWebAuthenticationPresentationContextProviding {

    /// Must match `NATIVE_CALLBACK_SCHEME` in `lib/auth/native-handoff.ts`.
    static let callbackScheme = "obelisk"

    /// Held for the lifetime of the sheet — `ASWebAuthenticationSession` is deallocated and the
    /// sheet vanishes if nothing retains it.
    private var session: ASWebAuthenticationSession?

    /// Run the flow and return a session, or throw.
    ///
    /// - Parameter provider: `"google"` today; the server accepts any provider its own OAuth routes
    ///   know, so adding one later needs no change here.
    func signIn(provider: String = "google", api: AccountAPI = .shared) async throws -> AccountSession {
        let verifier = Self.makeVerifier()
        let challenge = SHA256.base64URLDigest(of: verifier)

        var components = URLComponents(
            url: api.baseURL.appendingPathComponent("api/auth/oauth/\(provider)"),
            resolvingAgainstBaseURL: true)
        components?.queryItems = [
            URLQueryItem(name: "native", value: "1"),
            URLQueryItem(name: "challenge", value: challenge),
        ]
        guard let startURL = components?.url else { throw AccountError.badResponse }

        let callback = try await present(startURL: startURL)

        // The server bounces failures back onto the same scheme so the sheet always closes with a
        // reason, rather than leaving the pilot looking at a web page inside a modal.
        let query = URLComponents(url: callback, resolvingAgainstBaseURL: false)?.queryItems ?? []
        if let error = query.first(where: { $0.name == "error" })?.value {
            throw Self.mapServerError(error)
        }
        guard let code = query.first(where: { $0.name == "code" })?.value, !code.isEmpty else {
            throw AccountError.badResponse
        }

        return try await api.exchangeOAuth(code: code, verifier: verifier)
    }

    // MARK: The sheet

    private func present(startURL: URL) async throws -> URL {
        try await withCheckedThrowingContinuation { continuation in
            let session = ASWebAuthenticationSession(
                url: startURL,
                callbackURLScheme: Self.callbackScheme
            ) { callbackURL, error in
                if let error {
                    let code = (error as? ASWebAuthenticationSessionError)?.code
                    continuation.resume(throwing: code == .canceledLogin
                                        ? AccountError.cancelled
                                        : AccountError.offline)
                    return
                }
                guard let callbackURL else {
                    continuation.resume(throwing: AccountError.badResponse)
                    return
                }
                continuation.resume(returning: callbackURL)
            }

            session.presentationContextProvider = self
            // NOT ephemeral: a pilot already signed into Google in Safari should get the account
            // picker, not a password prompt. iOS shows its own "wants to use obeliskaerospace.com
            // to sign in" consent sheet first, which is the honest disclosure of exactly that.
            session.prefersEphemeralWebBrowserSession = false

            self.session = session
            if !session.start() {
                continuation.resume(throwing: AccountError.badResponse)
            }
        }
    }

    func presentationAnchor(for session: ASWebAuthenticationSession) -> ASPresentationAnchor {
        // The key window of the active foreground scene. An iPad in Split View has more than one
        // scene, and anchoring to the wrong one puts the sheet over the other app.
        let scenes = UIApplication.shared.connectedScenes
            .compactMap { $0 as? UIWindowScene }
        let anchor = scenes.first { $0.activationState == .foregroundActive }?
            .windows.first { $0.isKeyWindow }
            ?? scenes.first?.windows.first
        return anchor ?? ASPresentationAnchor()
    }

    // MARK: Helpers

    /// A high-entropy PKCE verifier. Lives only in this object's memory and in one POST body.
    private static func makeVerifier() -> String {
        var bytes = [UInt8](repeating: 0, count: 32)
        let status = SecRandomCopyBytes(kSecRandomDefault, bytes.count, &bytes)
        if status == errSecSuccess { return Data(bytes).base64URLEncodedString() }
        assertionFailure("WebOAuthSignIn: SecRandomCopyBytes failed (\(status))")
        return UUID().uuidString + UUID().uuidString
    }

    /// Turn the server's error slug into something worth showing a pilot.
    private static func mapServerError(_ slug: String) -> AccountError {
        switch slug {
        case "oauth_denied":
            return .cancelled
        case "oauth_unavailable", "unknown_provider":
            return .message("That sign-in option isn't available right now. Try email instead.")
        case "oauth_state":
            return .message("The sign-in attempt expired. Please try again.")
        default:
            return .message("Sign-in didn't complete. Please try again.")
        }
    }
}
